package bench

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/cruzamilcars/autotier/internal/catalog"
)

// Import aplica el blend al capability-catalog.yaml humano y regenera el
// overlay compilado catalog.gen.go. Idempotente y auditable: reporta cada
// celda cambiada con su procedencia.
type Applied struct {
	Cells    []Cell
	GenPath  string
	YamlPath string
	Sources  []Source
}

func Import(models []catalog.Model, sources []Source, wPrior, wEv float64, asOf string, halfLife, minF float64, repoRoot string) (Applied, error) {
	cells := Report(models, sources, wPrior, wEv, asOf, halfLife, minF)
	final := map[string]map[string]int{} // tier -> domain -> score
	for _, m := range models {
		final[m.ID] = map[string]int{}
		for d, s := range m.Scores {
			final[m.ID][d] = s
		}
	}
	for _, c := range cells {
		final[c.Tier][c.Domain] = c.Blended
	}
	genPath := filepath.Join(repoRoot, "internal", "catalog", "catalog.gen.go")
	yamlPath := filepath.Join(repoRoot, "internal", "catalog", "capability-catalog.yaml")
	if err := writeGen(genPath, cells, sources); err != nil {
		return Applied{}, err
	}
	if err := writeCatalogYAML(yamlPath, models, final, sources); err != nil {
		return Applied{}, err
	}
	return Applied{Cells: cells, GenPath: genPath, YamlPath: yamlPath, Sources: sources}, nil
}

func writeGen(path string, cells []Cell, sources []Source) error {
	byTier := map[string][]Cell{}
	for _, c := range cells {
		byTier[c.Tier] = append(byTier[c.Tier], c)
	}
	var tiers []string
	for t := range byTier {
		tiers = append(tiers, t)
	}
	sort.Strings(tiers)
	dateOf := map[string]string{}
	for _, s := range sources {
		dateOf[s.Name] = s.Date
	}
	// cellProv: "tier|dominio" -> "fuente@fecha, ..." solo contribuyentes.
	cellProv := map[string]string{}
	for _, c := range cells {
		seen := map[string]bool{}
		var parts []string
		for _, f := range c.From {
			name := f
			if i := strings.Index(f, ":"); i >= 0 {
				name = f[:i]
			}
			if !seen[name] {
				seen[name] = true
				parts = append(parts, name+"@"+dateOf[name])
			}
		}
		sort.Strings(parts)
		cellProv[c.Tier+"|"+c.Domain] = strings.Join(parts, ", ")
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by `autotier bench import`. DO NOT EDIT.\n")
	sb.WriteString("// Evidencia auditada de benchmarks publicos; ver internal/bench/data/.\n")
	sb.WriteString("package catalog\n\n")
	sb.WriteString("// generatedScores sobreescribe priors curados con blend evidencia+prior.\n")
	sb.WriteString("var generatedScores = map[string]Scores{\n")
	maxTier := 0
	for _, t := range tiers {
		if len(t) > maxTier {
			maxTier = len(t)
		}
	}
	for _, t := range tiers {
		cs := byTier[t]
		sort.Slice(cs, func(i, j int) bool { return cs[i].Domain < cs[j].Domain })
		fmt.Fprintf(&sb, "\t%q:%s{", t, strings.Repeat(" ", maxTier-len(t)+1))
		for i, c := range cs {
			if i > 0 {
				sb.WriteString(", ")
			}
			fmt.Fprintf(&sb, "%q: %d", c.Domain, c.Blended)
		}
		sb.WriteString("},\n")
	}
	sb.WriteString("}\n\n")
	sb.WriteString("// generatedProvenance documenta fuente y fecha por celda aplicada.\n")
	sb.WriteString("var generatedProvenance = map[string]string{\n")
	maxKey := 0
	var pkeys []string
	for k := range cellProv {
		pkeys = append(pkeys, k)
		if len(k) > maxKey {
			maxKey = len(k)
		}
	}
	sort.Strings(pkeys)
	for _, k := range pkeys {
		fmt.Fprintf(&sb, "\t%q:%s%q,\n", k, strings.Repeat(" ", maxKey-len(k)+1), cellProv[k])
	}
	sb.WriteString("}\n")
	return os.WriteFile(path, []byte(sb.String()), 0644)
}

func writeCatalogYAML(path string, models []catalog.Model, final map[string]map[string]int, sources []Source) error {
	var sb strings.Builder
	sb.WriteString("# Catalogo vivo auditado. Scores finales = blend(prior curado, evidencia).\n")
	sb.WriteString("# Regenerado por `autotier bench import`. Fuentes:\n")
	seen := map[string]bool{}
	for _, s := range sources {
		key := s.Name + "@" + s.Date
		if seen[key] {
			continue
		}
		seen[key] = true
		fmt.Fprintf(&sb, "# - %s [%s] %s (%s)\n", s.Name, s.Domain, s.URL, s.Date)
	}
	sb.WriteString("models:\n")
	for _, m := range models {
		fmt.Fprintf(&sb, "  - id: %s\n", m.ID)
		sb.WriteString("    examples: [")
		for i, e := range m.Examples {
			if i > 0 {
				sb.WriteString(", ")
			}
			sb.WriteString(e)
		}
		sb.WriteString("]\n")
		fmt.Fprintf(&sb, "    cost_in_per_1m: %.1f\n", m.CostInPer1M)
		fmt.Fprintf(&sb, "    cost_out_per_1m: %.1f\n", m.CostOutPer1M)
		fmt.Fprintf(&sb, "    context_window: %d\n", m.ContextWindow)
		fmt.Fprintf(&sb, "    latency_p95_ms: %d\n", m.LatencyP95Ms)
		var doms []string
		for d := range final[m.ID] {
			doms = append(doms, d)
		}
		sort.Strings(doms)
		var parts []string
		for _, d := range doms {
			parts = append(parts, fmt.Sprintf("%s: %d", d, final[m.ID][d]))
		}
		sb.WriteString("    scores: {" + strings.Join(parts, ", ") + "}\n")
	}
	sb.WriteString("\ntool_dialects:\n  kimi-k2: kimi_k2_vllm\n  kimi-k2-thinking: kimi_k2_vllm\n  default_kimi: openai_json_xml\n")
	return os.WriteFile(path, []byte(sb.String()), 0644)
}
